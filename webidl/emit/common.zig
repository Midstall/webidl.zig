test "generateChecked: malformed input returns HasDiagnostics and writes to err_w" {
    const src = "interface Bad { NoSuchType doThing(); };";
    var out: std.Io.Writer.Allocating = .init(testing.allocator);
    defer out.deinit();
    var err: std.Io.Writer.Allocating = .init(testing.allocator);
    defer err.deinit();
    const result = generateChecked(testing.allocator, src, .model, &out.writer, &err.writer, false);
    try testing.expectError(error.HasDiagnostics, result);
    try testing.expect(err.writer.buffered().len > 0);
    try testing.expectEqualStrings("", out.writer.buffered());
}

test "generateChecked: valid input emits and produces empty err_w" {
    const src = "enum E { \"a\", \"b\" };";
    var out: std.Io.Writer.Allocating = .init(testing.allocator);
    defer out.deinit();
    var err: std.Io.Writer.Allocating = .init(testing.allocator);
    defer err.deinit();
    try generateChecked(testing.allocator, src, .model, &out.writer, &err.writer, false);
    try testing.expect(out.writer.buffered().len > 0);
    try testing.expectEqualStrings("", err.writer.buffered());
}
