test "sortByName: sorts Enum slice" {
    var items = [_]model.Enum{
        .{ .name = "Zeta", .values = &.{} },
        .{ .name = "Alpha", .values = &.{} },
        .{ .name = "Mu", .values = &.{} },
    };
    sortByName(model.Enum, &items);
    try testing.expectEqualStrings("Alpha", items[0].name);
    try testing.expectEqualStrings("Mu", items[1].name);
    try testing.expectEqualStrings("Zeta", items[2].name);
}

test "generate: model smoke" {
    const src = "enum E { \"a\", \"b\" };";
    var aw: std.Io.Writer.Allocating = .init(testing.allocator);
    defer aw.deinit();
    try generate(testing.allocator, src, .model, &aw.writer);
    const out = aw.writer.buffered();
    try testing.expect(std.mem.indexOf(u8, out, "pub const E = enum {") != null);
}

